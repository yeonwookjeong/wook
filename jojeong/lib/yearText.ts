// One sentence per palace, however many of the four land there.
export function palaceLine(palace: string, kinds: string[]): string {
  const area = PALACE_AREA[palace];
  const goods = kinds.filter((k) => k !== "기");
  const bad = kinds.includes("기");
  if (palace === "질액")
    return bad
      ? "올해는 몸에서 먼저 신호가 오기 쉬우니, 검진과 치료를 미루지 마시옵소서."
      : "올해는 몸을 돌보는 일에 운이 붙으니, 운동이나 치료를 시작하기 좋사옵니다.";
  if (!goods.length) return `다만 올해는 ${area} 마음 쓸 일이 생기고 꼬이기 쉬우니, 가장 조심할 곳이옵니다.`;
  const head = goods.slice(0, -1).map((k) => GOOD[k][0] + " ");
  const last = GOOD[goods.at(-1)!];
  return bad
    ? `올해는 ${area} ${head.join("")}${last[0]}, 그만큼 마음 쓸 일도 따르니 방심은 금물이옵니다.`
    : `올해는 ${area} ${head.join("")}${last[1]}`;
}
