export function userPrompt(spec: ReportSpec, subjectLine: string, briefs: string): string {
  return `${subjectLine}

[이 보고서]
${spec.focus}

[장 순서 — 읽는 사람이 궁금해하는 질문들]
${spec.chapters.map((c, i) => `${i + 1}. ${c}`).join("\n")}

[사주 브리프]
${briefs}

위 브리프를 근거로, 각 질문에 정 훈도가 마주 앉아 답해 주듯 장 순서대로 써 주시옵소서.`;
}
