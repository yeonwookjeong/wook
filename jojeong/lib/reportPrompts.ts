export function userPrompt(spec: ReportSpec, subjectLine: string, briefs: string): string {
  return `${subjectLine}

[보고서 주제]
${spec.focus}

[장 순서] ${spec.chapters.map((c, i) => `${i + 1}. ${c}`).join(" / ")}

[사주 브리프]
${briefs}

위 브리프만 근거로, 장 순서대로 보고서를 써 주시옵소서.`;
}
