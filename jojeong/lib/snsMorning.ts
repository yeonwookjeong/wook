const ymd = (t: number) => {
  const x = new Date(t);
  return [x.getUTCFullYear(), x.getUTCMonth() + 1, x.getUTCDate()] as const;
};
const holiday = (t: number) => {
  const [y, m, d] = ymd(t);
  return holidaysOf(y).get(`${m}-${d}`) ?? null;
};
const isOff = (t: number) =>
  [0, 6].includes(new Date(t).getUTCDay()) || holiday(t) !== null;

// The reader's morning, from the calendar only (the weekday, holidays and the days off around them).
export function sceneOf(
  y: number,
  m: number,
  d: number,
): { off: boolean; scene: string } {
  const t = Date.UTC(y, m - 1, d);
  const wd = new Date(t).getUTCDay();
  const name = holiday(t);
  if (isOff(t)) {
    let first = t;
    while (isOff(first - DAYMS)) first -= DAYMS;
    let last = t;
    while (isOff(last + DAYMS)) last += DAYMS;
    const n = (last - first) / DAYMS + 1;
    const i = (t - first) / DAYMS;
    if (name === "추석" || name === "설날")
      return { off: true, scene: `${name} 아침` };
    if (wd === 0 && t < last)
      return { off: true, scene: "일요일인데 내일도 쉬는 날" };
    if (n >= 3 && n <= 10)
      return {
        off: true,
        scene:
          i === 0
            ? `${COUNT[n]} 연휴 첫날`
            : t === last
              ? "연휴 마지막 날"
              : `연휴 ${NTH[i]} 날`,
      };
    if (wd === 6 || wd === 0)
      return { off: true, scene: `${WEEK[wd]}요일 아침` };
    return { off: true, scene: `${name} 아침` };
  }
  // The first working day after three or more days off; the day before a weekday holiday.
  let back = t - DAYMS;
  let gap = 0;
  while (isOff(back)) {
    gap++;
    back -= DAYMS;
  }
  if (gap >= 3) return { off: false, scene: "연휴 끝나고 첫 출근날" };
  const next = holiday(t + DAYMS);
  if (next && wd < 5 && !next.includes("·"))
    return { off: false, scene: `내일이 ${next}인 ${WEEK[wd]}요일` };
  return { off: false, scene: `${WEEK[wd]}요일 아침` };
}

export type Morning = { gz: string; name: string; text: string };

// "2026-10-03" → the post for that Korean calendar day.
export function morningPost(date: string): Morning {
  const [y, m, d] = date.split("-").map(Number);
  const { stem, branch } = dayPillar(y, m, d);
  const gz = `${STEMS[stem]}${BRANCHES[branch]}`;
  const name = `${STEMS_KO[stem]}${BRANCHES_KO[branch]}`;
  const p = DAY[gz];
  const { off, scene } = sceneOf(y, m, d);
  const text = [
    `${m}월 ${d}일`,
    `오늘의 일진은 ${name}(${gz})이옵니다.`,
    `${p.pic}이지요.`,
    `${scene}, ${off ? p.off : p.on}`,
    `"오늘은 ${p.nick}"이라는 핑계를 빌려 드리겠사옵니다.`,
    p.why,
  ].join("\n");
  return { gz, name, text };
}
