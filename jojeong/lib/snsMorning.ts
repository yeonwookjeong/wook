export type Morning = { gz: string; name: string; text: string };

// "2026-10-02" → the post for that Korean calendar day.
export function morningPost(date: string): Morning {
  const [y, m, d] = date.split("-").map(Number);
  const { stem, branch } = dayPillar(y, m, d);
  const gz = `${STEMS[stem]}${BRANCHES[branch]}`;
  const name = `${STEMS_KO[stem]}${BRANCHES_KO[branch]}`;
  const [like, fit] = DAY_LINE[gz];
  const text = [`${m}월 ${d}일의 일진은 ${name}(${gz})이옵니다.`, `${ILJU_IMAGE[gz]} 같은 날이지요.`, `${like},`, `${fit}에 어울리는 날이옵니다.`].join("\n");
  return { gz, name, text };
}
