export const columnBySlug = (slug: string) =>
  COLUMNS.find((c) => c.slug === slug) ?? null;

// Today in Korea, as YYYY-MM-DD: an article dated later is written but not yet public.
export const kstToday = () =>
  new Date(Date.now() + 9 * 3600000).toISOString().slice(0, 10);
export const isPublished = (c: Column) => c.date <= kstToday();
// Newest first.
export const publishedColumns = () =>
  COLUMNS.filter(isPublished).sort((a, b) => b.date.localeCompare(a.date));

// The title as shown: the topic, then the subtitle on a line of its own. "A, B" → ["A", "B"]; "A? B" → ["A?", "B"].
export const titleLines = (title: string): [string, string?] => {
  const m = title.match(/^(.+?)(,|\?)\s+(.+)$/);
  return m ? [m[2] === "?" ? `${m[1]}?` : m[1], m[3]] : [title];
};

// "2026-10-07" → "2026년 10월 7일"
export const columnDate = (d: string) => {
  const [y, m, day] = d.split("-").map(Number);
  return `${y}년 ${m}월 ${day}일`;
};
